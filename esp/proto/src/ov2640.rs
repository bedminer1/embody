/// Everything `set_framesize` writes for one output size, in order:
/// bypass the DSP, write `mode` then `window`, set the clocks, re-enable the
/// DSP, then re-send [`JPEG`] (required after a size change).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FrameSize {
    pub mode: &'static [(u8, u8)],
    /// DSP-bank input window and output (zoom) size.
    pub window: [(u8, u8); 10],
    /// Sensor-bank `CLKRC`.
    pub clkrc: u8,
    /// DSP-bank `R_DVP_SP` (pixel clock divider).
    pub dvp_sp: u8,
}

/// Register values for a 4:3 JPEG output of `width` x `height`, or `None`
/// if the size is not 4:3, not a multiple of 4, or above 1600x1200.
pub fn frame_size(width: u16, height: u16) -> Option<FrameSize> {
    if width == 0
        || !width.is_multiple_of(4)
        || !height.is_multiple_of(4)
        || u32::from(width) * 3 != u32::from(height) * 4
        || width > 1600
    {
        return None;
    }
    // The 4:3 entry of the C driver's ratio table (the whole 1600x1200
    // sensor), scaled to the readout mode. CIF readout stops at 296 lines.
    let (mode, max_x, max_y, dvp_sp): (_, u16, u16, u8) = if width <= 400 && height <= 296 {
        (MODE_CIF, 400, 296, 8)
    } else if width <= 800 && height <= 600 {
        (MODE_SVGA, 800, 600, 8)
    } else {
        (MODE_UXGA, 1600, 1200, 12)
    };
    let (max_x, max_y) = (max_x / 4, max_y / 4);
    let (w, h) = (width / 4, height / 4);
    // Offsets are zero for 4:3, so their bits are omitted below.
    let window = [
        (BANK_SEL, BANK_DSP),
        (0x51, (max_x & 0xff) as u8),
        (0x52, (max_y & 0xff) as u8),
        (0x53, 0),
        (0x54, 0),
        (0x55, (((max_y >> 1) & 0x80) | ((max_x >> 5) & 0x08)) as u8),
        (0x57, ((max_x >> 2) & 0x80) as u8),
        (0x5a, (w & 0xff) as u8),
        (0x5b, (h & 0xff) as u8),
        (0x5c, zoom_high(w, h)),
    ];
    Some(FrameSize {
        mode,
        window,
        // JPEG: no clock doubling or division; fixed pixel clock divider.
        clkrc: 0x00,
        dvp_sp,
    })
}

/// `ZMHH`: bit 2 is bit 8 of the output height / 4, bits 0-1 bits 8-9 of
/// the width / 4.
fn zoom_high(w: u16, h: u16) -> u8 {
    (((h >> 6) & 0x04) | ((w >> 8) & 0x03)) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vga_uses_svga_readout() {
        let size = frame_size(640, 480).unwrap();
        assert_eq!(size.mode, MODE_SVGA);
        assert_eq!(size.window[1], (0x51, 200));
        assert_eq!(size.window[2], (0x52, 150));
        assert_eq!(size.window[5], (0x55, 0));
        assert_eq!(size.window[7], (0x5a, 160));
        assert_eq!(size.window[8], (0x5b, 120));
        assert_eq!((size.clkrc, size.dvp_sp), (0, 8));
        assert_eq!(size.window[9], (0x5c, 0));
    }

    #[test]
    fn qvga_uses_cif_readout_capped_at_296_lines() {
        let size = frame_size(320, 240).unwrap();
        assert_eq!(size.mode, MODE_CIF);
        assert_eq!(size.window[1], (0x51, 100));
        assert_eq!(size.window[2], (0x52, 74));
    }

    #[test]
    fn uxga_sets_high_bits() {
        let size = frame_size(1600, 1200).unwrap();
        assert_eq!(size.window[5], (0x55, 0x80 | 0x08));
        assert_eq!(size.window[6], (0x57, 0));
        assert_eq!(size.window[9], (0x5c, 0x04 | 0x01));
        assert_eq!(size.dvp_sp, 12);
        assert_eq!(zoom_high(400, 300), 0x04 | 0x01);
    }

    #[test]
    fn rejects_other_shapes() {
        assert_eq!(frame_size(480, 320), None);
        assert_eq!(frame_size(642, 481), None);
        assert_eq!(frame_size(2048, 1536), None);
    }
}
